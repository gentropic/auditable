#!/usr/bin/env node
// Generate @gcu/proj's EPSG table — EVERY projected + geographic-2D CRS that has a proj4
// definition (no curated subset: "it makes no sense to pick"), with its name, area-of-use box,
// area description, unit and the accuracy of its default transformation to WGS 84.
//
//   npm pack epsg-index@2.0.0 && mkdir e && tar xzf epsg-index-2.0.0.tgz -C e
//   node ext/proj/tools/gen-epsg.mjs e/package
//
// Source: epsg-index (ISC, © Jannis R) — a machine-readable dump of the EPSG Geodetic Parameter
// Dataset (via epsg.io). Stored COLUMNAR (one array per field, repeated strings as indices)
// because that gzips far better than rows, then gzip + base64 into src/data-epsg.js, which the
// library inflates on first use with DecompressionStream (nothing at startup; no network).
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = process.argv[2];
if (!dir) { console.error('usage: node gen-epsg.mjs <extracted epsg-index package dir>'); process.exit(1); }
const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
const rawBytes = fs.readFileSync(path.join(dir, 'all.json'));
const all = JSON.parse(rawBytes.toString('utf8'));
const rows = Object.values(all)
  .filter((e) => (e.kind === 'CRS-PROJCRS' || e.kind === 'CRS-GEOGCRS') && e.proj4)
  .sort((a, b) => +a.code - +b.code);
const strip = (d) => d.replace(/\s*\+no_defs\b/g, '').replace(/\s*\+type=crs\b/g, '').trim();
const unitOf = (u) => (u == null ? '' : String(u).replace(/\s*\(supplier to define representation\)/, ''));
const intern = () => { const list = [], at = new Map(); return { list, id: (s) => { if (!at.has(s)) { at.set(s, list.length); list.push(s); } return at.get(s); } }; };
const units = intern(), areas = intern();
const cols = {
  v: 1,
  code: rows.map((e) => +e.code),
  kind: rows.map((e) => (e.kind === 'CRS-PROJCRS' ? 'p' : 'g')).join(''),
  name: rows.map((e) => e.name).join('\n'),
  def: rows.map((e) => strip(e.proj4)).join('\n'),
  // [west, south, east, north] — epsg-index stores [north, west, south, east]
  bbox: rows.flatMap((e) => (Array.isArray(e.bbox) ? [e.bbox[1], e.bbox[2], e.bbox[3], e.bbox[0]] : [null, null, null, null])),
  unit: rows.map((e) => units.id(unitOf(e.unit))),
  area: rows.map((e) => areas.id(e.area || '')),
  acc: rows.map((e) => (e.accuracy == null || e.accuracy === '' ? null : +e.accuracy)),
  units: units.list,
  areas: areas.list,
};
const json = JSON.stringify(cols);
const gz = zlib.gzipSync(Buffer.from(json, 'utf8'), { level: 9, mtime: 0 });
// gzip header bytes 4..7 are the mtime (0 here) and byte 9 the OS: pin it so the output is reproducible
gz[9] = 255;
const b64 = gz.toString('base64');
const source = {
  package: 'epsg-index', version: pkg.version, licence: 'ISC', file: 'all.json',
  sha256: crypto.createHash('sha256').update(rawBytes).digest('hex'),
  dataset: 'EPSG Geodetic Parameter Dataset (via epsg.io)',
  count: rows.length, projected: rows.filter((e) => e.kind === 'CRS-PROJCRS').length, geographic: rows.filter((e) => e.kind === 'CRS-GEOGCRS').length,
  rawBytes: json.length, gzipBytes: gz.length,
};
const out = `// GENERATED by ext/proj/tools/gen-epsg.mjs from ${source.package}@${source.version} (${source.licence}; ${source.dataset}).
// ${source.count} CRS (${source.projected} projected + ${source.geographic} geographic 2D), columnar JSON, gzip + base64
// (${(source.rawBytes / 1024).toFixed(0)} KB raw → ${(source.gzipBytes / 1024).toFixed(0)} KB gzip). Never edit — regenerate.
export const EPSG_SOURCE = ${JSON.stringify(source)};
export const EPSG_GZ_B64 = '${b64}';
`;
fs.writeFileSync(path.join(here, '..', 'src', 'data-epsg.js'), out);
const vj = path.join(here, '..', 'vendor', 'VENDOR.json');
const prev = fs.existsSync(vj) ? JSON.parse(fs.readFileSync(vj, 'utf8')) : {};
prev['epsg-index'] = { version: source.version, file: source.file, sha256: source.sha256, licence: 'ISC', count: source.count };
fs.writeFileSync(vj, JSON.stringify(prev, null, 2) + '\n');
console.log(`EPSG table: ${source.count} CRS (${source.projected} projected, ${source.geographic} geographic) · ${(source.rawBytes / 1024).toFixed(0)} KB raw · ${(source.gzipBytes / 1024).toFixed(0)} KB gzip · ${(b64.length / 1024).toFixed(0)} KB base64`);
