#!/usr/bin/env node
// Generate @gcu/proj's world outline — Natural Earth 1:110m LAND (public domain), for the CRS
// selector's little map (area of use + the data's extent). From world-atlas's TopoJSON:
//
//   npm pack world-atlas@2.0.2 && mkdir w && tar xzf world-atlas-2.0.2.tgz -C w
//   node ext/proj/tools/gen-world.mjs w/package
//
// The TopoJSON arcs are stitched into closed rings (lon/lat), quantized to 0.01°, consecutive
// duplicates dropped, rings under 3 points dropped, then stored delta-coded as Int32 (an
// antimeridian jump overflows Int16) →
// gzip → base64 in src/data-world.js. Layout: [ringCount, (n, x0, y0, dx1, dy1, …)×ringCount]
// in units of 0.01°. Natural Earth is public domain; world-atlas (the TopoJSON packaging) is ISC.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = process.argv[2];
if (!dir) { console.error('usage: node gen-world.mjs <extracted world-atlas package dir>'); process.exit(1); }
const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
const raw = fs.readFileSync(path.join(dir, 'land-110m.json'));
const topo = JSON.parse(raw.toString('utf8'));
const [sx, sy] = topo.transform.scale, [tx, ty] = topo.transform.translate;
const arcs = topo.arcs.map((a) => { let x = 0, y = 0; return a.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; }); });
const arcPts = (i) => (i >= 0 ? arcs[i] : arcs[~i].slice().reverse());
const ringOf = (idx) => { const out = []; idx.forEach((i, k) => { const p = arcPts(i); out.push(...(k ? p.slice(1) : p)); }); return out; };
const polys = [];
for (const g of topo.objects.land.geometries) {
  if (g.type === 'Polygon') polys.push(g.arcs);
  else if (g.type === 'MultiPolygon') polys.push(...g.arcs);
}
const Q = 100;                                              // 0.01°
const out = [0];
let rings = 0, pts = 0;
for (const poly of polys) for (const idx of poly) {
  const q = [];
  for (const [x, y] of ringOf(idx)) {
    const X = Math.round(x * Q), Y = Math.round(y * Q);
    if (q.length && q[q.length - 1][0] === X && q[q.length - 1][1] === Y) continue;
    q.push([X, Y]);
  }
  if (q.length > 1 && q[0][0] === q[q.length - 1][0] && q[0][1] === q[q.length - 1][1]) q.pop();
  if (q.length < 3) continue;
  out.push(q.length, q[0][0], q[0][1]);
  for (let i = 1; i < q.length; i++) out.push(q[i][0] - q[i - 1][0], q[i][1] - q[i - 1][1]);
  rings++; pts += q.length;
}
out[0] = rings;
const bytes = Buffer.from(new Int32Array(out).buffer);
const gz = zlib.gzipSync(bytes, { level: 9, mtime: 0 });
gz[9] = 255;
const source = { data: 'Natural Earth 1:110m land (public domain)', package: 'world-atlas', version: pkg.version, licence: 'ISC (packaging); data public domain', file: 'land-110m.json', sha256: crypto.createHash('sha256').update(raw).digest('hex'), rings, points: pts, quantum: 1 / Q, gzipBytes: gz.length };
fs.writeFileSync(path.join(here, '..', 'src', 'data-world.js'), `// GENERATED by ext/proj/tools/gen-world.mjs — ${source.data}, via ${source.package}@${source.version}.
// ${rings} rings, ${pts} points at ${1 / Q}°, Int32 delta-coded, gzip + base64 (${(gz.length / 1024).toFixed(1)} KB). Never edit — regenerate.
export const WORLD_SOURCE = ${JSON.stringify(source)};
export const WORLD_GZ_B64 = '${gz.toString('base64')}';
`);
const vj = path.join(here, '..', 'vendor', 'VENDOR.json');
const prev = fs.existsSync(vj) ? JSON.parse(fs.readFileSync(vj, 'utf8')) : {};
prev['world-atlas'] = { version: source.version, file: source.file, sha256: source.sha256, licence: source.licence };
fs.writeFileSync(vj, JSON.stringify(prev, null, 2) + '\n');
console.log(`world: ${rings} rings · ${pts} points · ${(gz.length / 1024).toFixed(1)} KB gzip`);
