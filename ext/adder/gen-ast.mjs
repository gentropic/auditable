#!/usr/bin/env node
// Generates pylib/_ast.py — the node classes CPython's ast.py is written over — from a CPython 3.13
// interpreter's own _ast: each class's name, base, _fields, _attributes and field types, so a node
// made here has CPython's shape (Module(body, type_ignores), BinOp(left, op, right) …).
//   node ext/adder/gen-ast.mjs [python]     (needs CPython 3.13: `python` on PATH by default)
// The constructor is CPython 3.13's AST.__init__: positional arguments by _fields, keywords, and a
// field left out its default — [] for a list, None for an optional one, Load() for a context;
// any other field left out is a DeprecationWarning (and stays unset), as in 3.13.
import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const python = process.argv[2] || 'python';
const dump = execFileSync(python, ['-I', '-c', `
import _ast, json, sys
out = {}
for name in sorted(dir(_ast)):
    c = getattr(_ast, name)
    if isinstance(c, type) and issubclass(c, _ast.AST):
        ft = getattr(c, '_field_types', {})
        out[name] = {
            'base': c.__mro__[1].__name__ if c is not _ast.AST else None,
            'fields': list(c._fields), 'attributes': list(c._attributes),
            'types': {k: (v.__name__ if isinstance(v, type) else repr(v).replace('ast.', '')) for k, v in ft.items()},
            'doc': c.__doc__ or '',
            'nones': sorted(k for k, v in vars(c).items() if v is None and k != '__doc__'),
        }
consts = {k: getattr(_ast, k) for k in dir(_ast) if k.startswith('PyCF_')}
json.dump({'version': sys.version.split()[0], 'nodes': out, 'consts': consts}, sys.stdout)
`], { encoding: 'utf8' });
const { version, nodes, consts } = JSON.parse(dump);
if (!version.startsWith('3.13')) throw new Error(`gen-ast: needs CPython 3.13 (got ${version})`);

// classes in an order where every base comes first
const order = [];
const seen = new Set();
const visit = (n) => { if (seen.has(n)) return; seen.add(n); if (nodes[n].base) visit(nodes[n].base); order.push(n); };
for (const n of Object.keys(nodes)) visit(n);

const pyStr = (s) => JSON.stringify(s);
const tup = (a) => (a.length === 0 ? '()' : a.length === 1 ? `(${pyStr(a[0])},)` : `(${a.map(pyStr).join(', ')})`);

let out = `# _ast: the node classes of CPython 3.13's abstract syntax tree, as CPython's C module defines
# them — generated by ext/adder/gen-ast.mjs from CPython ${version}'s own _ast (names, bases,
# _fields, _attributes, field types). ast.py (CPython's, verbatim) is written over these; adder's
# compile(..., PyCF_ONLY_AST) builds them from its parser (_from_tree).
# Part of adder (MIT); the class table is CPython's (PSF License 2.0, see LICENSE-PSF.txt).

import warnings as _warnings

${Object.entries(consts).map(([k, v]) => `${k} = ${v}`).join('\n')}



class AST:
    _fields = ()
    _attributes = ()
    __match_args__ = ()

    # CPython 3.13's ast_type_init: positional arguments by _fields, keywords; then each field left
    # out by its type in the class's _field_types — a list one is [], a context one Load(), an
    # optional one None (from the class), any other a DeprecationWarning (and stays unset); a field
    # not in _field_types a warning too. A class without _field_types isn't checked.
    def __init__(self, *args, **kwargs):
        cls = type(self)
        fields = cls._fields
        if len(args) > len(fields):
            raise TypeError(f"{cls.__name__} constructor takes at most "
                            f"{len(fields)} positional argument{'' if len(fields) == 1 else 's'}")
        for name, value in zip(fields, args):
            setattr(self, name, value)
        for name, value in kwargs.items():
            if name in fields[:len(args)]:
                raise TypeError(f"{cls.__name__} got multiple values for argument {name!r}")
            if name not in fields and name not in cls._attributes:
                _warnings.warn(f"{cls.__name__}.__init__ got an unexpected keyword argument {name!r}. "
                               f"Support for arbitrary keyword arguments is deprecated and will be "
                               f"removed in Python 3.15.", DeprecationWarning, stacklevel=2)
            setattr(self, name, value)
        if len(args) + len(kwargs) >= len(fields):
            given = set(fields[:len(args)]) | set(kwargs)
            if all(name in given for name in fields):
                return
        try:
            types = cls._field_types
        except AttributeError:
            return
        for name in fields[len(args):]:
            if name in kwargs:
                continue
            if name not in types:
                _warnings.warn(f"Field {name!r} is missing from {cls.__name__}._field_types. "
                               f"This will become an error in Python 3.15.", DeprecationWarning, stacklevel=2)
                continue
            kind = _kind_of(types[name])
            if kind == 'list':
                setattr(self, name, [])
            elif kind == 'load':
                setattr(self, name, Load())
            elif kind == 'required':
                _warnings.warn(f"{cls.__name__}.__init__ missing 1 required positional argument: {name!r}. "
                               f"This will become an error in Python 3.15.", DeprecationWarning, stacklevel=2)

    def __reduce__(self):
        # (None for each field up to the last required one, as CPython's: the remade node then
        # takes its state — remade without arguments, it would warn of the missing ones)
        cls = type(self)
        types = getattr(cls, '_field_types', {})
        n = 0
        for i, name in enumerate(cls._fields):
            if name not in types or _kind_of(types[name]) == 'required':
                n = i + 1
        return cls, (None,) * n, dict(self.__dict__)

    def __replace__(self, **kwargs):
        cls = type(self)
        for name in kwargs:
            if name not in cls._fields and name not in cls._attributes:
                raise TypeError(f"{cls.__name__}.__replace__ got an unexpected keyword argument {name!r}.")
        values = {name: getattr(self, name) for name in cls._fields + cls._attributes if hasattr(self, name)}
        values.update(kwargs)
        return cls(**values)


# what a field left out of a constructor gets, by its type: 'list' (list[X]), 'load' (a context),
# 'none' (X | None: the class's None), 'required'
def _kind_of(t):
    if getattr(t, '__origin__', None) is list:
        return 'list'
    if type(None) in getattr(t, '__args__', ()):
        return 'none'
    if t is expr_context:
        return 'load'
    return 'required'

AST.__module__ = 'ast'
AST.__annotations__ = {}
`;
const fieldTypes = [];
for (const name of order) {
  if (name === 'AST') continue;
  const n = nodes[name];
  const body = [];
  if (n.doc) body.push(`    ${pyStr(n.doc)}`);
  // a class repeats what it inherits only where it differs (CPython's do too)
  body.push(`    _fields = ${tup(n.fields)}`);
  body.push(`    _attributes = ${tup(n.attributes)}`);
  body.push(`    __match_args__ = ${tup(n.fields)}`);
  // (an optional field, and an optional position, is None on the class itself — ast.dump leaves
  // out a field whose value is the class's)
  for (const k of n.nones) body.push(`    ${k} = None`);
  out += `\n\nclass ${name}(${n.base}):\n${body.join('\n')}\n${name}.__module__ = 'ast'\n`;
  // (the signature line, ast's documentation of the node: on the class as CPython has it)
  if (n.doc) out += `${name}.__doc__ = ${pyStr(n.doc)}\n`;
  // (the field types, and __annotations__ — the same, as CPython's node classes carry them)
  // (a class without fields has empty annotations — every node class has them)
  if (!Object.keys(n.types).length) out += `${name}.__annotations__ = {}\n`;
  else fieldTypes.push(`${name}._field_types = {${Object.entries(n.types).map(([k, v]) => `${pyStr(k)}: ${v}`).join(', ')}}\n${name}.__annotations__ = dict(${name}._field_types)`);
}

out += `

# each class's field types: real types (list[expr], expr | None), set once every class exists —
# ast.dump tells a list field by its type's __origin__
${fieldTypes.join('\n')}


# ── from adder's parser ──
# compile(source, …, PyCF_ONLY_AST) hands its tree over as plain dicts: {'_type': 'BinOp', 'left':
# …, 'lineno': …}; a float, a complex or the Ellipsis arrives as {'_k': 'float' | 'complex' |
# 'Ellipsis', 'v': …}. A node with no fields (Load, Add, …) is one shared instance, as CPython's are.
_SINGLETONS = {}


def _from_tree(t):
    if isinstance(t, list):
        return [_from_tree(x) for x in t]
    if not isinstance(t, dict):
        return t
    k = t.get('_k')
    if k is not None:
        if k == 'float':
            return float(t['v'])
        if k == 'complex':
            return complex(0, t['v'])
        if k == 'Ellipsis':
            return ...
        raise ValueError(k)
    name = t['_type']
    cls = globals()[name]
    if not cls._fields and not cls._attributes:
        node = _SINGLETONS.get(name)
        if node is None:
            node = _SINGLETONS[name] = cls()
        return node
    node = cls.__new__(cls)
    for f in cls._fields:
        setattr(node, f, _from_tree(t.get(f)))
    for a in cls._attributes:
        if a in t:
            setattr(node, a, t[a])
    return node
`;
const file = path.join(here, 'pylib', '_ast.py');
fs.writeFileSync(file, out);
console.log(`wrote ${path.relative(process.cwd(), file)}: ${order.length} classes (CPython ${version})`);
