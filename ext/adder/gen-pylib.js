#!/usr/bin/env node
// Embeds the Python-source stdlib modules in pylib/ into src/stdlib-py.js (frozen modules:
// imported like any stdlib module, compiled by whichever engine the program runs on).
//   pylib/<a>/<b>.py         → module a.b
//   pylib/<a>/__init__.py    → package a
// Run after changing pylib/ (build.js runs it first).
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, 'pylib');
const out = path.join(here, 'src', 'stdlib-py.js');

const entries = [];
(function walk(dir, parts) {
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) { if (name !== '__pycache__') walk(full, [...parts, name]); continue; }
    if (!name.endsWith('.py')) continue;
    const pkg = name === '__init__.py';
    const modName = (pkg ? parts : [...parts, name.slice(0, -3)]).join('.');
    entries.push([modName, { pkg, source: fs.readFileSync(full, 'utf8').replace(/\r\n/g, '\n') }]);
  }
})(root, []);

const body = entries.map(([n, e]) => `  ${JSON.stringify(n)}: { pkg: ${e.pkg}, source: ${JSON.stringify(e.source)} },`).join('\n');
const js = `// GENERATED by ext/adder/gen-pylib.js from ext/adder/pylib/ — do not edit; edit the .py files.
// adder stdlib modules written in Python (frozen modules): ${entries.map(([n]) => n).join(', ')}
// (html.parser and _markupbase are CPython's own, PSF License 2.0 — see pylib/README.md and pylib/LICENSE-PSF.txt)

import { frozenPyModules } from './builtins.js';

Object.assign(frozenPyModules, {
${body}
});
`;
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
if (prev !== js) fs.writeFileSync(out, js);
console.log(`stdlib-py.js: ${entries.length} frozen modules${prev === js ? ' (unchanged)' : ''}`);
