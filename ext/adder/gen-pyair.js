#!/usr/bin/env node
// Precompiles the frozen stdlib modules most programs import (the HOT list) into
// src/stdlib-pyair.js: each module AIR-compiled exactly as an import compiles it (runner.js
// compileModuleSource), then its local names mangled by terser (mangle only — no other
// transform: gzip pays mostly for the compiler's unique temp names). An import of one of these on
// AIR then skips parse, lowering, passes and emission; the tree-walker still runs the .py.
//
// Each artifact records `emit`, a hash of the UNMANGLED emitted JS: test/adder-pyair.test.mjs
// recompiles every module and compares, so a compiler change that alters the output fails the
// test until this runs again (build.js runs it on every build). The same hash lets a rerun skip
// terser for a module whose output didn't change.
//   node ext/adder/gen-pyair.js
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { createRequire } from 'module';
import { fileURLToPath, pathToFileURL } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, 'src', 'stdlib-pyair.js');

// the bundled set: what a typical program pulls in. The rest of pylib (unittest, doctest, pydoc,
// difflib, tokenize, xml, html.parser, _pyrepl, …) compiles on first import, as before.
export const HOT = [
  '__future__', '_collections_abc', 'dataclasses',
  'json', 'json.decoder', 'json.encoder', 'json.scanner',
  'argparse', 'glob', 'shutil',
  'importlib._bootstrap', 'importlib._bootstrap_external',
];

const require = createRequire(import.meta.url);
const { minify } = require('terser');
const imp = (p) => import(pathToFileURL(path.join(here, p)).href);
const A = await imp('src/index.js');
A.attachAir(await imp('../air/index.js'));
const { compileModuleSource } = await imp('src/runner.js');

// a module's .py and package, as the frozen loader sees them (eval.js findModule)
function sourceOf(name) {
  const parts = name.split('.');
  const asFile = path.join(here, 'pylib', ...parts) + '.py';
  if (fs.existsSync(asFile)) return { src: fs.readFileSync(asFile, 'utf8'), pkg: parts.slice(0, -1).join('.') };
  return { src: fs.readFileSync(path.join(here, 'pylib', ...parts, '__init__.py'), 'utf8'), pkg: name };
}
const hash = (s) => crypto.createHash('sha256').update(s).digest('hex').slice(0, 20);

// the previous artifacts: reused when the emitted JS is unchanged
const prev = {};
if (fs.existsSync(out)) {
  const m = fs.readFileSync(out, 'utf8').match(/^\/\/ DATA\n([\s\S]*)\n\/\/ END DATA$/m);
  if (m) Object.assign(prev, JSON.parse(m[1]));
}

const artifacts = {};
for (const name of HOT) {
  const { src, pkg } = sourceOf(name);
  const c = compileModuleSource(src.replace(/\r\n/g, '\n'), { kind: 'module', package: pkg });
  const emit = hash(c.body);
  if (prev[name] && prev[name].emit === emit) { artifacts[name] = prev[name]; continue; }
  const fnSrc = `(${c.async ? 'async ' : ''}function (_py${c.imports.map((n) => ', ' + n).join('')}) {\n${c.body}\n})`;
  const r = await minify(fnSrc, { mangle: true, compress: false, ecma: 2022, format: { comments: false, ecma: 2022 } });
  artifacts[name] = { emit, imports: c.imports, doc: c.doc, code: r.code.replace(/;$/, '') };
}

const body = JSON.stringify(artifacts, null, 0).replace(/^\{/, '{\n').replace(/,"(?=[^"]+":\{"emit")/g, ',\n"');
const js = `// GENERATED by ext/adder/gen-pyair.js from ext/adder/pylib/ — do not edit; run the script.
// AIR-compiled frozen modules (${HOT.join(', ')}): see gen-pyair.js.

import { frozenPyCompiled } from './builtins.js';

const _frozenPyairData =
// DATA
${body}
// END DATA
;
Object.assign(frozenPyCompiled, _frozenPyairData);
`;
const before = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
if (before !== js) fs.writeFileSync(out, js);
console.log(`stdlib-pyair.js: ${HOT.length} precompiled modules, ${(js.length / 1024).toFixed(0)} KB${before === js ? ' (unchanged)' : ''}`);
