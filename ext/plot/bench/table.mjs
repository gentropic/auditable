// BENCH.md from bench/results/*.json — the numbers are never typed by hand.
//   node ext/plot/bench/table.mjs [old-label] [new-label]      (default 0.1.1 0.2.0)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const [oldL = '0.1.1', newL = '0.2.0'] = process.argv.slice(2);
const load = (l) => JSON.parse(fs.readFileSync(path.join(here, 'results', `${l}.json`), 'utf8'));
const A = load(oldL), B = load(newL);

// the spec's targets (plot-world-class-SPEC.md §6): [case, what, first ms, again ms]
const TARGETS = [
  ['trivial', 'import + a trivial figure', 20, null],
  ['scatter_1M', 'scatter, 1M points, colour-mapped, 2 px markers', 150, 20],
  ['scatter_500k', 'scatter, 500k points, colour-mapped', 80, null],
  ['line_1M', 'line, 1M vertices', 30, null],
  ['hist_10M', 'hist, 10M values, 100 bins', 60, null],
  ['imshow_2000', 'imshow 2,000 × 2,000', 60, 5],
  ['contourf_500', 'contourf 500 × 500, 10 levels', 100, null],
  ['pick_1M', 'hover pick, 1M points (first = index build)', 30, 1],
];

const fmt = (r, k) => {
  if (!r) return '—';
  if (r.note) return r.note.replace(/\|/g, '/');
  const v = r[k];
  if (v == null) return '—';
  return v < 1 ? v.toFixed(3) : v < 10 ? v.toFixed(1) : String(Math.round(v));
};
const met = (r, first, again) => {
  if (!r || r.note) return '';
  const ok = r.first <= first && (again == null || r.again == null || r.again <= again);
  return ok ? '✓' : '✗';
};

let md = `# @gcu/plot bench

Generated by \`node ext/plot/bench/table.mjs ${oldL} ${newL}\` from \`bench/results/\`. Run the
bench with \`node ext/plot/bench/run.mjs --label <name>\` (headless Chromium through Playwright;
each case × mode in a fresh page, the median of several runs). Times are milliseconds.

- **first** — building the figure's data on the axes and drawing it once (data generation is
  not timed). **again** — drawing the same figure, same view, a second time.
- **canvas** — \`fig.draw(ctx)\` on a real 2D canvas (the read-back of one pixel forces the
  raster to finish). **record** — \`fig.toDrawList()\`, the no-DOM path; "ops" is its length.
- Targets are the spec's (§6), stated once and not moved; a miss is recorded with its number.
- This machine (a laptop, other work running) is noisy: across four full 0.2.0 passes the
  medians spanned scatter 500k 63–87 ms, imshow 52–95, line 26–46, hist 65–86, others ±15%.
  The table is the last pass (7 runs per case), not the best one.

| | |
|---|---|
| machine | ${B.machine} |
| browser | Chromium ${B.chromium} |
| ${oldL} | ${A.at.slice(0, 10)}, entry \`${A.entry}\` |
| ${newL} | ${B.at.slice(0, 10)}, entry \`${B.entry}\` |

| case | target first / again | ${oldL} canvas | ${newL} canvas first / again | | ${oldL} record | ${newL} record first / again | ops | |
|---|---|---|---|---|---|---|---|---|
`;
for (const [k, what, tf, ta] of TARGETS) {
  const ac = A.results[`${k}/canvas`], ar = A.results[`${k}/record`];
  const bc = B.results[`${k}/canvas`], br = B.results[`${k}/record`];
  const oldCell = (r) => (r && !r.note ? `${fmt(r, 'first')}${r.again != null ? ' / ' + fmt(r, 'again') : ''}` : fmt(r));
  const newCell = (r) => (r && !r.note ? `${fmt(r, 'first')}${r.again != null ? ' / ' + fmt(r, 'again') : ''}` : fmt(r));
  md += `| ${what} | ${tf}${ta != null ? ' / ' + ta : ''} | ${oldCell(ac)} | ${newCell(bc)} | ${met(bc, tf, ta)} | ${oldCell(ar)} | ${newCell(br)} | ${br && br.ops != null ? br.ops : '—'} | ${met(br, tf, ta)} |\n`;
}
md += `
## Notes on the misses and the method

- **0.1.1 scatters on a canvas time out**: one \`arc\` + \`fill\` per point; past ~100k points the
  canvas takes minutes. Its scatter also silently dropped \`c\` given as a typed array (D1), so
  0.1.1's numbers are for uniform-colour points. Its 10M hist dies in \`Math.min(...data)\` (D2).
- **hist 10M** sits around the 60 ms target, sometimes over: two passes over 80 MB (the
  finite range, then the counts). The counting loop keeps numpy's exact edge rule — a value
  within a hair of an edge is checked against the real edges — which costs a few ms and is
  what makes the counts match \`numpy.histogram\` exactly (test/fixtures/plot-numpy-hist.json).
- **imshow, record mode**: most of the time is base64-encoding 16 MB of RGBA into the draw
  list's one \`image\` op (a table encoder, ~6× faster than \`btoa\`). The canvas path skips it.
- **line 1M "again"**: on a real canvas the decimated path is cached as a \`Path2D\`; a draw
  list has no Path2D, so recording writes its ~10k vertices each time.
- **contourf 500 × 500** (M2): over 40,000 cells on a rectilinear grid, the bands rasterize —
  each device pixel takes the band of the same four-triangle field the contour lines follow —
  into one image (166 ops). Smaller grids, and \`{vector: true}\`, draw polygons: cells inside a
  band merge into one rectangle per row-run, only crossed cells split into triangles. The first
  M2 version drew a polygon per triangle per band: 22 million ops, 3 s recorded, over 90 s on a
  canvas.
- **What "first" times changed in M2**: the cases now time the chart call itself (ingest,
  counting) as well as the first draw, as "first" was always defined. In 0.2.0 only the draw
  was timed, which was the same thing while histograms counted lazily at draw time; M2's
  \`hist()\` counts at the call (it returns \`[n, bins, patches]\`), and timing only the draw read
  8 ms. The trivial figure's 13 → 18 ms is the bigger bundle's parse at import.
- **M3** changes no draw path; the cases above sit within the machine's noise of M2. The
  trivial figure, import included, is 20 ms against a 20 ms target: the everything-bundle grew
  from 270 to 338 KB raw (SVG export, the PNG encoder, interaction), and its parse is most of
  that time. A host that wants less imports less: \`@gcu/plot/svg\` and \`@gcu/plot/interact\` are
  their own entries.
`;
fs.writeFileSync(path.join(here, 'BENCH.md'), md);
console.log(md);
