// Regenerate tools/wuffle/src/samples.js from tools/wuffle/samples/*.csv — the built single file can't fetch,
// so the samples ship as strings. test/wuffle-io.test.mjs fails if the two drift apart.
//   node tools/wuffle/dev/gen-samples.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../', import.meta.url);
const tocher = readFileSync(new URL('samples/tocher.csv', dir), 'utf8');
const out = '// GENERATED by tools/wuffle/dev/gen-samples.mjs from tools/wuffle/samples/ — do not edit by hand\n'
  + `export const TOCHER = ${JSON.stringify(tocher)};\n`;
writeFileSync(new URL('src/samples.js', dir), out);
console.log(`samples.js: tocher ${tocher.length} chars`);
