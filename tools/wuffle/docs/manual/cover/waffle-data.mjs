// The waffle's geometry, from wuffle's own maths: everything a 3D renderer needs, in the unit disc of a
// lower-hemisphere equal-area (Schmidt) net — x east, y north, the primitive at radius 1.
//   graticule — the net's 10° great circles (N–S) and small circles (about the N–S axis): the waffle's ridges
//   chips     — the 200 Tocher (1979) poles, projected: the chocolate chips
//   syrup     — Kamb contours (k = 3) of those poles at 4σ and 8σ: the syrup's pool and its deepest part
//
//   node tools/wuffle/docs/manual/cover/waffle-data.mjs   → cover/waffle.json
import { readFile, writeFile } from 'fs/promises';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';
import * as B from '../../../../../ext/bearing/index.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../../../../..');
const csv = await readFile(join(ROOT, 'tools/wuffle/samples/tocher.csv'), 'utf8');
const planes = csv.split('\n').filter((l) => /^\d/.test(l)).map((l) => l.split(',').map(Number));
const poles = planes.map(([dd, dip]) => B.conversions.planeToDcos(dd, dip));

// lower-hemisphere equal-area, normalised so the primitive is r = 1: (x, y) / sqrt(1 − z), z ≤ 0
const proj = (d) => { let [x, y, z] = d; if (z > 0) { x = -x; y = -y; z = -z; } const k = 1 / Math.sqrt(1 - z); return [x * k, y * k]; };
const rnd = (p) => p.map((v) => Math.round(v * 1e5) / 1e5);

// the graticule: great circles striking N–S (dips 10…80 east and west, and the vertical one), and small
// circles about the N–S axis (half-angles 10…80 at both ends) — the Schmidt net's own lines
const graticule = [];
const sample = (f, n = 240) => Array.from({ length: n + 1 }, (_, i) => f(i / n));
for (let dip = 10; dip <= 90; dip += 10) for (const side of dip === 90 ? [1] : [1, -1]) {
  // the plane through the N–S line dipping `dip` toward east (side 1) or west: its points from N through the dip line to S
  const c = Math.cos(dip * Math.PI / 180), s = Math.sin(dip * Math.PI / 180);
  graticule.push(sample((t) => { const a = Math.PI * t; return rnd(proj([side * Math.sin(a) * c, Math.cos(a), -Math.sin(a) * s])); }));
}
for (let ang = 10; ang < 90; ang += 10) for (const end of [1, -1]) {
  // the cone of half-angle `ang` about the horizontal N (end 1) or S axis, its lower half
  const ca = Math.cos(ang * Math.PI / 180), sa = Math.sin(ang * Math.PI / 180);
  graticule.push(sample((t) => { const b = Math.PI * t; return rnd(proj([sa * Math.cos(b), end * ca, -sa * Math.sin(b)])); }));
}

// the chips: every pole
const chips = poles.map((d) => rnd(proj(d)));

// the syrup: Kamb contours, from a Stereonet so they are exactly the ones wuffle draws — converted from svg
// coordinates back to the unit disc
const SIZE = 2000, net = new B.Stereonet({ size: SIZE, padding: 0, projection: 'equal-area' });
const c0 = net.project([0, 0, -1]), e0 = net.project([1, 0, 0]), R = e0.x - c0.x;
const toUnit = ([sx, sy]) => rnd([(sx - c0.x) / R, -(sy - c0.y) / R]);
net.contour(poles, { method: 'kamb', kambSigma: 3, gridSize: 200, levels: [4, 8] });
net.updateContours();
const syrup = {};
for (const lvl of net._contourPaths) syrup[lvl.level] = lvl.paths.map((path) => path.map(([px, py]) => toUnit(net._toSvg(px, py))));

// the Kamb density field itself (k = 3, values in σ), on a grid over the unit disc: the syrup lies where it is
// ≥ 4σ (its edge IS the 4σ contour) and runs deeper where the poles crowd. Row j = north to south, column i =
// west to east, x = −1 + i·step, y = 1 − j·step; NaN (null) outside the net.
const dg = B.densityGrid(poles, { method: 'kamb', kambSigma: 3, gridSize: 241, projection: 'equal-area' });
const kamb = { size: dg.gridSize, step: dg.step / dg.projR, values: Array.from(dg.grid, (v) => (Number.isFinite(v) ? Math.round(v * 1000) / 1000 : null)) };

await writeFile(join(HERE, 'waffle.json'), JSON.stringify({
  note: 'Tocher (1979) on a lower-hemisphere equal-area net, unit disc, x east, y north; generated by waffle-data.mjs',
  graticule, chips, syrup, kamb,
}));
console.log(`waffle: ${graticule.length} graticule curves, ${chips.length} chips, syrup levels ${Object.keys(syrup).join(', ')} (${Object.values(syrup).map((p) => p.length).join(' / ')} rings)`);
